    public static (int Best, int Worst)? Days(int rank, int target, bool firstInFc)
    {
        var curve = firstInFc ? FirstInFc : Later;
        var max = curve.GetLength(0);
        if (rank < 1 || target > max) return null;
        if (rank >= target) return (0, 0);
        var best = curve[target - 1, 0] - curve[rank - 1, 0];
        var worst = curve[target - 1, 2] - curve[rank - 1, 2];
        var lo = (int)Math.Ceiling(Math.Max(Math.Min(best, worst), 0));
        var hi = (int)Math.Ceiling(Math.Max(Math.Max(best, worst), 0));
        return (lo, hi);
    }

    /// <summary>The highest target rank the baseline covers for that kind of sub.</summary>
    public static int MaxRank(bool firstInFc) => (firstInFc ? FirstInFc : Later).GetLength(0);

